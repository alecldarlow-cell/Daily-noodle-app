#!/usr/bin/env node
/*
 * Copies the site's own rules into packages/core/vendor/ so the differential tests can
 * compare @noodle/core against the real thing, without a site clone in CI.
 *
 *   node scripts/vendor-site.js --site ../dailynoodle          # write vendor files
 *   node scripts/vendor-site.js --site ../dailynoodle --check  # exit 1 if they're stale
 *
 * dn-core.js is copied verbatim. Functions from front.js and the engines are lifted
 * by name (brace-matched), each engine in its own scope, with stubs for what they
 * touch (storage, the streak UI), and exported for the tests. Nothing is rewritten.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const args = process.argv.slice(2);
const site = path.resolve(args[args.indexOf('--site') + 1] || '');
const check = args.includes('--check');
if (!fs.existsSync(path.join(site, 'dn-core.js'))) {
  console.error(
    'Usage: node scripts/vendor-site.js --site <path to a dailynoodle clone> [--check]',
  );
  process.exit(2);
}
const OUT = path.join(__dirname, '..', 'packages', 'core', 'vendor');
const read = (rel) => fs.readFileSync(path.join(site, rel), 'utf8');

/**
 * The full text of a top-level declaration named `name`: a function (to its closing
 * brace) or a const (to its first semicolon outside brackets and strings).
 */
function lift(src, name, file) {
  const re = new RegExp(
    `(^|\\n)[ \\t]*((?:async\\s+)?function\\s+${name}\\s*\\(|const\\s+${name}\\s*=)`,
  );
  const m = re.exec(src);
  if (!m) throw new Error(`${file}: no declaration of ${name}`);
  const start = m.index + m[1].length;
  const isFn = /function/.test(m[2]);
  let depth = 0;
  let quote = null;
  let seenBody = false;
  // A function's scan starts at its own '(' (the last character of the match).
  for (let i = start + m[2].length - (isFn ? 1 : 0); i < src.length; i++) {
    const c = src[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') quote = c;
    else if (c === '{' || c === '(' || c === '[') {
      depth++;
      if (c === '{') seenBody = true;
    } else if (c === '}' || c === ')' || c === ']') {
      depth--;
      if (isFn && c === '}' && depth === 0 && seenBody) return src.slice(start, i + 1).trim();
    } else if (!isFn && c === ';' && depth === 0) return src.slice(start, i + 1).trim();
  }
  throw new Error(`${file}: could not find the end of ${name}`);
}

function scopeOf(file, names, prelude = '') {
  const src = read(file);
  const body = names.map((n) => lift(src, n, file)).join('\n');
  return `(() => {\n${prelude}${body}\nreturn { ${names.join(', ')} };\n})()`;
}

let sha = 'unknown';
try {
  sha = execSync('git rev-parse HEAD', { cwd: site }).toString().trim();
} catch {}

const shared = `
  // The engines' own helpers, as each engine defines them.
  function today(){return env.londonDay();}
  function dayBefore(s){return env.dayBefore(s);}
`;
const site_js = `// GENERATED by scripts/vendor-site.js from alecldarlow-cell/dailynoodle@${sha}. Do not edit.
// The site's own functions, lifted verbatim, for @noodle/core's differential tests.
'use strict';
module.exports = function load(env) {
  const localStorage = env.localStorage;
  const window = { dnCore: env.dnCore };
  let streakDoc = null;
  const store = async () => streakDoc;
  const saveStreak = async (s) => { streakDoc = s; return true; };
  const refreshStreakUI = () => {};
  let ranked = true;
  const front = ${scopeOf('front.js', ['clock', 'shownClock', 'num', 'resultText', 'playedState'])};
  const mini = ${scopeOf('engines/mini.js', ['followsOn', 'bumpStreak'], shared)};
  const sweep = ${scopeOf('engines/sweep.js', ['followsOn', 'recordResult'], shared)};
  const link = ${scopeOf('engines/link.js', ['followsOn', 'recordResult', 'GLYPH', 'dnTime', 'dnStreak', 'dnNum', 'dnLinkRow', 'dnLink'], shared)};
  const path = ${scopeOf('engines/path.js', ['STREAK_KEY', 'streakGet', 'streakLive', 'streakBump'], shared)};
  const doku = ${scopeOf('engines/doku.js', ['dokuStreakSeed'], shared)};
  const sweepShare = ${scopeOf('engines/sweep.js', ['dnTime', 'dnStreak', 'dnNum', 'dnSweepDay', 'dnSweep'])};
  const tangle = ${scopeOf('engines/tangle.js', ['plural'])};
  return {
    front, mini, sweep, link, path, doku, sweepShare, tangle,
    /** Set the grid streak document the lifted bumpStreak/recordResult read and write. */
    setStreak(s) { streakDoc = s; },
    getStreak() { return streakDoc; },
  };
};
`;

const files = {
  'dn-core.js': read('dn-core.js'),
  'site.js': site_js,
  'SOURCE.md': `# Vendored from the site\n\nGenerated by \`scripts/vendor-site.js\` from \`alecldarlow-cell/dailynoodle\` at\n\`${sha}\`. Used only by the differential tests; never imported by the app.\n\n- \`dn-core.js\`: verbatim copy.\n- \`site.js\`: functions lifted by name from \`front.js\` and \`engines/*.js\`.\n\nRegenerate after the site changes any of them:\n\n\`\`\`sh\nnode scripts/vendor-site.js --site ../dailynoodle\n\`\`\`\n`,
};

fs.mkdirSync(OUT, { recursive: true });
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const p = path.join(OUT, name);
  const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  if (check) {
    // The commit line legitimately differs; compare the code.
    const strip = (s) => (s || '').replace(/dailynoodle@[0-9a-f]+|at\n`[0-9a-f]+`/g, '');
    if (strip(cur) !== strip(text)) {
      stale++;
      console.log(`stale: ${name}`);
    }
  } else fs.writeFileSync(p, text);
}
if (check) process.exit(stale ? 1 : 0);
console.log(`vendored from ${sha} into ${path.relative(process.cwd(), OUT)}`);
